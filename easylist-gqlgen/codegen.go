package easylistgql

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
	"strings"

	easylist "github.com/mgpnd/easylist-go/easylist-core"

	"github.com/99designs/gqlgen/codegen/templates"
)

const (
	coreImport = "github.com/mgpnd/easylist-go/easylist-core"
	selfImport = "github.com/mgpnd/easylist-go/easylist-gqlgen"
)

// goField is one field of a generated row struct or method.
type goField struct {
	f       easylist.Field
	goName  string // gqlgen's Go name for the GraphQL field
	elem    string // Go type of the value, or of each element of an array
	goType  string // non-pointer Go type: elem, or a slice of it
	accessr string // easylist.Row accessor
}

func goFields(l *easylist.CompiledList) ([]goField, error) {
	var out []goField
	seen := map[string]string{}
	for _, f := range l.Fields() {
		// gqlgen matches fields case-insensitively and ignoring underscores,
		// so names equal under that rule cannot both be bound.
		key := strings.ToLower(strings.ReplaceAll(f.Name, "_", ""))
		if other, dup := seen[key]; dup {
			return nil, fmt.Errorf("list %q: fields %q and %q map to the same Go name", l.Name(), other, f.Name)
		}
		seen[key] = f.Name
		g := goField{f: f, goName: templates.ToGo(f.Name)}
		switch f.Type {
		case easylist.Integer:
			g.elem, g.accessr = "int64", "Int64"
		case easylist.Float:
			g.elem, g.accessr = "float64", "Float64"
		case easylist.Boolean:
			g.elem, g.accessr = "bool", "Bool"
		case easylist.Date, easylist.Timestamp:
			g.elem, g.accessr = "time.Time", "Time"
		case easylist.Enum:
			g.elem, g.accessr = l.TypePrefix()+easylist.PascalCase(f.Name), "String"
		default:
			g.elem, g.accessr = "string", "String"
		}
		g.goType = g.elem
		if f.Array {
			// The plural accessors (Strings, Int64s, ...) return slices.
			g.goType, g.accessr = "[]"+g.elem, g.accessr+"s"
		}
		out = append(out, g)
	}
	return out, nil
}

// generateGo returns the formatted Go file holding the bindings for every list.
// registryPkg and registryName locate the *easylist.Registry used at runtime.
func generateGo(pkgName, registryPkg, registryName string, lists []*easylist.CompiledList) ([]byte, error) {
	var body bytes.Buffer
	usesTime, usesContext := false, false
	for _, l := range lists {
		fields, err := goFields(l)
		if err != nil {
			return nil, err
		}
		for _, g := range fields {
			usesTime = usesTime || g.elem == "time.Time"
			usesContext = usesContext || g.f.Calculated()
		}
		writeList(&body, l, fields)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by easylist-gqlgen. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\nimport (\n", pkgName)
	b.WriteString("\t\"context\"\n\t\"io\"\n")
	if usesTime {
		b.WriteString("\t\"time\"\n")
	}
	fmt.Fprintf(&b, "\n\teasylist %q\n\teasylistgql %q\n\teasylistdefs %q\n)\n\n", coreImport, selfImport, registryPkg)
	fmt.Fprintf(&b, "func registry() *easylist.Registry { return easylistdefs.%s }\n\n", registryName)
	if !usesContext {
		b.WriteString("var _ context.Context\n\n")
	}
	b.Write(body.Bytes())

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("easylistgql: formatting generated code: %w\n%s", err, b.Bytes())
	}
	return out, nil
}

func writeList(b *bytes.Buffer, l *easylist.CompiledList, fields []goField) {
	p := l.TypePrefix()
	lower := strings.ToLower(p[:1]) + p[1:]
	name := strconv.Quote(l.Name())

	// Row.
	fmt.Fprintf(b, "// %sRow is one row of list %s. SQL fields are set when selected;\n// calculated fields are methods evaluated on demand.\n", p, name)
	fmt.Fprintf(b, "type %sRow struct {\n", p)
	for _, g := range fields {
		if g.f.Calculated() {
			continue
		}
		// A nil slice is a NULL array, so arrays need no pointer.
		ptr := ""
		if g.f.Nullable && !g.f.Array {
			ptr = "*"
		}
		fmt.Fprintf(b, "\t%s %s%s\n", g.goName, ptr, g.goType)
	}
	b.WriteString("\n\trow easylist.Row\n}\n\n")

	fmt.Fprintf(b, "func new%sRow(r easylist.Row) *%sRow {\n\tout := &%sRow{row: r}\n", p, p, p)
	for _, g := range fields {
		if g.f.Calculated() {
			continue
		}
		fmt.Fprintf(b, "\tif v, ok := r.%s(%q); ok {\n", g.accessr, g.f.Name)
		val := "v"
		if g.f.Type == easylist.Enum {
			val = g.goType + "(v)"
		}
		if g.f.Array {
			if g.f.Type == easylist.Enum {
				writeEnumSlice(b, "\t\t", "out."+g.goName, "v", g.elem)
			} else {
				fmt.Fprintf(b, "\t\tout.%s = v\n", g.goName)
			}
		} else if g.f.Nullable {
			fmt.Fprintf(b, "\t\tx := %s\n\t\tout.%s = &x\n", val, g.goName)
		} else {
			fmt.Fprintf(b, "\t\tout.%s = %s\n", g.goName, val)
		}
		b.WriteString("\t}\n")
	}
	b.WriteString("\treturn out\n}\n\n")

	for _, g := range fields {
		if !g.f.Calculated() {
			continue
		}
		val := "v.(" + g.goType + ")"
		if g.f.Type == easylist.Enum {
			val = g.goType + "(v.(string))"
		}
		fmt.Fprintf(b, "// %s evaluates calculated field %q for this row.\n", g.goName, g.f.Name)
		if g.f.Array {
			// A nil slice is NULL, so nullable and non-nullable arrays share a signature.
			fmt.Fprintf(b, "func (r *%sRow) %s(ctx context.Context) (%s, error) {\n", p, g.goName, g.goType)
			fmt.Fprintf(b, "\tv, err := r.row.Calc(ctx, %q)\n\tif err != nil || v == nil {\n\t\treturn nil, err\n\t}\n", g.f.Name)
			if g.f.Type == easylist.Enum {
				b.WriteString("\tin := v.([]string)\n\tvar out " + g.goType + "\n")
				writeEnumSlice(b, "\t", "out", "in", g.elem)
				b.WriteString("\treturn out, nil\n}\n\n")
			} else {
				fmt.Fprintf(b, "\treturn %s, nil\n}\n\n", val)
			}
		} else if g.f.Nullable {
			fmt.Fprintf(b, "func (r *%sRow) %s(ctx context.Context) (*%s, error) {\n", p, g.goName, g.goType)
			fmt.Fprintf(b, "\tv, err := r.row.Calc(ctx, %q)\n\tif err != nil || v == nil {\n\t\treturn nil, err\n\t}\n", g.f.Name)
			fmt.Fprintf(b, "\tx := %s\n\treturn &x, nil\n}\n\n", val)
		} else {
			fmt.Fprintf(b, "func (r *%sRow) %s(ctx context.Context) (%s, error) {\n", p, g.goName, g.goType)
			fmt.Fprintf(b, "\tv, err := r.row.Calc(ctx, %q)\n\tif err != nil {\n\t\tvar zero %s\n\t\treturn zero, err\n\t}\n", g.f.Name, g.goType)
			fmt.Fprintf(b, "\treturn %s, nil\n}\n\n", val)
		}
	}

	// Page.
	fmt.Fprintf(b, "type %sPage struct {\n\tItems      []*%sRow\n\tTotalCount int\n}\n\n", p, p)

	// Enums.
	for _, g := range fields {
		if g.f.Type == easylist.Enum {
			pairs := make([]string, 0, 2*len(g.f.Values))
			for _, v := range g.f.Values {
				pairs = append(pairs, v, easylist.EnumName(v))
			}
			writeEnum(b, g.elem, fmt.Sprintf("holds a declared value of field %q", g.f.Name), pairs)
		}
	}
	var sortPairs, exportPairs []string
	for _, g := range fields {
		pair := []string{g.f.Name, easylist.EnumName(g.f.Name)}
		if sortable(g.f) {
			sortPairs = append(sortPairs, pair...)
		}
		exportPairs = append(exportPairs, pair...)
	}
	writeEnum(b, p+"SortField", "holds the name of a sortable field", sortPairs)
	writeEnum(b, p+"ExportField", "holds the name of an exportable field", exportPairs)

	// Inputs.
	fmt.Fprintf(b, "type %sSort struct {\n\tField     %sSortField\n\tDirection easylistgql.SortDirection\n}\n\n", p, p)
	fmt.Fprintf(b, "type %sListInput struct {\n\tFilter *string\n\tSort   []*%sSort\n\tLimit  *int\n\tOffset *int\n}\n\n", p, p)
	fmt.Fprintf(b, "type %sExportInput struct {\n\tFields []%sExportField\n\tFilter *string\n\tSort   []*%sSort\n\tFormat easylistgql.ExportFormat\n}\n\n", p, p, p)

	fmt.Fprintf(b, "func %sSorts(in []*%sSort) []easylist.Sort {\n\tout := make([]easylist.Sort, 0, len(in))\n", lower, p)
	b.WriteString("\tfor _, s := range in {\n\t\tif s != nil {\n\t\t\tout = append(out, easylist.Sort{Field: string(s.Field), Direction: easylist.Direction(s.Direction)})\n\t\t}\n\t}\n\treturn out\n}\n\n")

	// Resolvers.
	fmt.Fprintf(b, "// Resolve%s resolves a field returning %sPage. Only the fields selected\n// under items are queried, and the count runs only when totalCount is selected.\n", p, p)
	fmt.Fprintf(b, "func Resolve%s(ctx context.Context, rt *easylist.Runtime, input %sListInput) (*%sPage, error) {\n", p, p, p)
	fmt.Fprintf(b, "\tres, err := easylistgql.ResolveList(ctx, rt, registry(), %s, easylistgql.ListInput{\n", name)
	fmt.Fprintf(b, "\t\tFilter: input.Filter, Sort: %sSorts(input.Sort), Limit: input.Limit, Offset: input.Offset,\n\t})\n", lower)
	b.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
	fmt.Fprintf(b, "\tpage := &%sPage{TotalCount: res.TotalCount, Items: make([]*%sRow, len(res.Rows))}\n", p, p)
	fmt.Fprintf(b, "\tfor i, r := range res.Rows {\n\t\tpage.Items[i] = new%sRow(r)\n\t}\n\treturn page, nil\n}\n\n", p)

	fmt.Fprintf(b, "// Export%s validates an export of list %s and hands it to rt.Exporter.\n", p, name)
	fmt.Fprintf(b, "func Export%s(ctx context.Context, rt *easylist.Runtime, input %sExportInput) (*easylistgql.ExportJob, error) {\n", p, p)
	b.WriteString("\tfields := make([]string, len(input.Fields))\n\tfor i, f := range input.Fields {\n\t\tfields[i] = string(f)\n\t}\n")
	fmt.Fprintf(b, "\treturn easylistgql.Export(ctx, rt, registry(), %s, easylistgql.ExportInput{\n", name)
	fmt.Fprintf(b, "\t\tFields: fields, Filter: input.Filter, Sort: %sSorts(input.Sort), Format: input.Format,\n\t})\n}\n\n", lower)
}

// writeEnumSlice writes code that converts the []string src into a slice of
// the enum type elem and assigns it to dst.
func writeEnumSlice(b *bytes.Buffer, indent, dst, src, elem string) {
	fmt.Fprintf(b, "%s%s = make([]%s, len(%s))\n", indent, dst, elem, src)
	fmt.Fprintf(b, "%sfor i, s := range %s {\n%s\t%s[i] = %s(s)\n%s}\n", indent, src, indent, dst, elem, indent)
}

func writeEnum(b *bytes.Buffer, typeName, doc string, pairs []string) {
	lower := strings.ToLower(typeName[:1]) + typeName[1:]
	fmt.Fprintf(b, "// %s %s.\ntype %s string\n\n", typeName, doc, typeName)
	fmt.Fprintf(b, "var %sEnum = easylistgql.NewEnum[%s](%q", lower, typeName, typeName)
	for _, s := range pairs {
		fmt.Fprintf(b, ", %q", s)
	}
	b.WriteString(")\n\n")
	fmt.Fprintf(b, "func (e %s) MarshalGQL(w io.Writer) { %sEnum.Marshal(w, e) }\n\n", typeName, lower)
	fmt.Fprintf(b, "func (e *%s) UnmarshalGQL(v any) (err error) {\n\t*e, err = %sEnum.Unmarshal(v)\n\treturn err\n}\n\n", typeName, lower)
}
