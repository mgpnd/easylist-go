// Package easylistgql is a gqlgen plugin and runtime that expose easylist
// lists as GraphQL types. The plugin injects each list's SDL and generates
// its Go bindings in one gqlgen run; the application attaches list queries
// and export mutations wherever it wants in its own schema.
package easylistgql

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	easylist "github.com/mgpnd/easylist-go/easylist-core"

	"github.com/99designs/gqlgen/codegen/config"
	"github.com/99designs/gqlgen/plugin"
	"github.com/vektah/gqlparser/v2/ast"
)

// Options configures the plugin.
type Options struct {
	// Registry is the Go reference to the package-level *easylist.Registry
	// the generated code uses at runtime, such as
	// "example.com/app/lists.Registry". It must be the same registry passed
	// to NewPlugin, and its package must not import gqlgen-generated code.
	Registry string
	// Filename is the generated Go file. It defaults to
	// easylistgen/easylist_gen.go in the directory of the gqlgen exec package.
	Filename string
	// Package is the generated package name. It defaults to the base name of
	// Filename's directory.
	Package string
	// Scalars renames the custom scalars.
	Scalars Scalars
}

// Plugin is the gqlgen plugin. Add it with api.PrependPlugin so it binds the
// list types before gqlgen's model generator runs.
type Plugin struct {
	reg  *easylist.Registry
	opts Options
}

var (
	_           plugin.EarlySourcesInjector = (*Plugin)(nil)
	_           plugin.ConfigMutator        = (*Plugin)(nil)
	graphQLName                             = regexp.MustCompile(`^[_A-Za-z][_0-9A-Za-z]*$`)
)

// NewPlugin returns a plugin generating types for every list in reg.
func NewPlugin(reg *easylist.Registry, opts Options) *Plugin {
	opts.Scalars = opts.Scalars.withDefaults()
	return &Plugin{reg: reg, opts: opts}
}

// Name implements plugin.Plugin.
func (*Plugin) Name() string { return "easylist" }

// SchemaDir is the directory, relative to gqlgen's working directory (the
// directory of gqlgen.yml), where the plugin writes the SDL it injects.
// gqlgen embeds schema files in the generated exec package, so the injected
// sources must exist on disk.
const SchemaDir = "easylist"

// InjectSourcesEarly adds one SDL source per list and one shared source, and
// writes them under SchemaDir. A type that already exists in the application
// schema makes gqlgen fail with an error naming it.
func (p *Plugin) InjectSourcesEarly() ([]*ast.Source, error) {
	if err := p.check(); err != nil {
		return nil, err
	}
	lists := p.reg.Lists()
	sources := []*ast.Source{{Name: SchemaDir + "/shared.graphqls", Input: sharedSDL(lists, p.opts.Scalars)}}
	for _, l := range lists {
		sources = append(sources, &ast.Source{Name: SchemaDir + "/" + l.Name() + ".graphqls", Input: listSDL(l, p.opts.Scalars)})
	}
	if err := writeSources(sources); err != nil {
		return nil, err
	}
	return sources, nil
}

// writeSources replaces the .graphqls files in SchemaDir with sources.
func writeSources(sources []*ast.Source) error {
	if err := os.MkdirAll(SchemaDir, 0o755); err != nil {
		return err
	}
	old, err := filepath.Glob(filepath.Join(SchemaDir, "*.graphqls"))
	if err != nil {
		return err
	}
	for _, f := range old {
		if err := os.Remove(f); err != nil {
			return err
		}
	}
	for _, s := range sources {
		header := "# Code generated by easylist-gqlgen. DO NOT EDIT.\n\n"
		if err := os.WriteFile(filepath.FromSlash(s.Name), []byte(header+s.Input), 0o644); err != nil {
			return err
		}
		s.Input = header + s.Input
	}
	return nil
}

func (p *Plugin) check() error {
	if p.reg == nil {
		return errors.New("easylistgql: NewPlugin needs a registry")
	}
	if _, _, err := splitRef(p.opts.Registry); err != nil {
		return err
	}
	s := p.opts.Scalars
	seen := map[string]bool{}
	for _, name := range []string{s.Int64, s.Decimal, s.Date, s.UUID, s.Time} {
		if !graphQLName.MatchString(name) {
			return fmt.Errorf("easylistgql: invalid scalar name %q", name)
		}
		if seen[name] {
			return fmt.Errorf("easylistgql: scalar name %q is used twice", name)
		}
		seen[name] = true
	}
	return nil
}

func splitRef(ref string) (pkg, name string, err error) {
	i := strings.LastIndex(ref, ".")
	if i <= 0 || i < strings.LastIndex(ref, "/") || i == len(ref)-1 {
		return "", "", fmt.Errorf("easylistgql: Options.Registry %q must look like \"example.com/app/lists.Registry\"", ref)
	}
	return ref[:i], ref[i+1:], nil
}

// MutateConfig writes the generated Go file and binds every injected type to
// its Go type, as gqlgen's own model generator does.
func (p *Plugin) MutateConfig(cfg *config.Config) error {
	regPkg, regName, err := splitRef(p.opts.Registry)
	if err != nil {
		return err
	}
	filename := p.opts.Filename
	if filename == "" {
		filename = filepath.Join(filepath.Dir(cfg.Exec.Filename), "easylistgen", "easylist_gen.go")
	}
	if filename, err = filepath.Abs(filename); err != nil {
		return err
	}
	pkgName := p.opts.Package
	if pkgName == "" {
		pkgName = filepath.Base(filepath.Dir(filename))
	}
	out := config.PackageConfig{Filename: filename, Package: pkgName}
	if err := out.Check(); err != nil {
		return fmt.Errorf("easylistgql: %w", err)
	}
	importPath := out.ImportPath()
	if importPath == "" {
		return fmt.Errorf("easylistgql: cannot determine the import path of %s", filename)
	}

	lists := p.reg.Lists()
	src, err := generateGo(pkgName, regPkg, regName, lists)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(filename), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filename, src, 0o644); err != nil {
		return err
	}

	bind := func(gqlName, goRef string) {
		cfg.Models[gqlName] = config.TypeMapEntry{Model: config.StringList{goRef}}
	}
	s := p.opts.Scalars
	bind("SortDirection", selfImport+".SortDirection")
	bind("ExportFormat", selfImport+".ExportFormat")
	bind("ExportJob", selfImport+".ExportJob")
	used := usedScalars(lists, s)
	for name, ref := range map[string]string{
		s.Int64: selfImport + ".Int64", s.Decimal: selfImport + ".Decimal", s.Date: selfImport + ".Date",
		s.UUID: selfImport + ".UUID", s.Time: "github.com/99designs/gqlgen/graphql.Time",
	} {
		if used[name] {
			bind(name, ref)
		}
	}
	for _, l := range lists {
		pre := l.TypePrefix()
		for _, suffix := range []string{"Row", "Page", "SortField", "Sort", "ListInput", "ExportField", "ExportInput"} {
			bind(pre+suffix, importPath+"."+pre+suffix)
		}
		for _, f := range l.Fields() {
			if f.Type == easylist.Enum {
				name := pre + easylist.PascalCase(f.Name)
				bind(name, importPath+"."+name)
			}
		}
	}
	cfg.ReloadAllPackages()
	return nil
}
