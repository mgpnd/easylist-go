// registryRef is the Go reference to lists.Registry that the gqlgen plugin
// takes in its options.
const registryRef = "github.com/mgpnd/easylist-go/easylist-behavior/lists.Registry"

// TestListSnapshots writes, for every fixture list, testdata/lists/<list>.golden
// holding the SDL the gqlgen plugin generates for the list and the operator
// matrix of its fields, and writes the plugin's shared SDL to
// testdata/lists/shared.golden.
func TestListSnapshots(t *testing.T) {
	// Nothing here reads the database, but no snapshot test may write
	// outcome files without one.
	openDB(t)

	sdl := pluginSDL(t)
	keep := map[string]bool{"shared.golden": true}
	golden(t, "lists/shared.golden", sdl["shared"])
	for _, l := range lists.Registry.Lists() {
		listSDL, ok := sdl[l.Name()]
		if !ok {
			t.Fatalf("the gqlgen plugin generated no SDL for list %q", l.Name())
		}
		keep[l.Name()+".golden"] = true
		golden(t, "lists/"+l.Name()+".golden", listSnapshot(l, listSDL))
	}
	prune(t, "lists", keep, ".golden")
}

// generatedHeader matches the header the gqlgen plugin puts on the SDL files
// it writes. The snapshots leave it out, like the plugin's own golden test.
var generatedHeader = regexp.MustCompile(`\A# Code generated .* DO NOT EDIT\.\n\n`)

// pluginSDL returns the SDL sources the gqlgen plugin injects for
// lists.Registry, keyed by the source's base name without its extension:
// "shared" and one entry per list name. The plugin also writes the sources
// under its schema directory relative to the working directory, so it runs
// in a temporary directory.
func pluginSDL(t *testing.T) map[string]string {
	t.Helper()
	wd, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	if err := os.Chdir(t.TempDir()); err != nil {
		t.Fatal(err)
	}
	sources, injectErr := easylistgql.NewPlugin(lists.Registry, easylistgql.Options{Registry: registryRef}).InjectSourcesEarly()
	if err := os.Chdir(wd); err != nil {
		t.Fatal(err)
	}
	if injectErr != nil {
		t.Fatal(injectErr)
	}
	out := map[string]string{}
	for _, s := range sources {
		name := strings.TrimSuffix(path.Base(s.Name), path.Ext(s.Name))
		out[name] = generatedHeader.ReplaceAllString(s.Input, "")
	}
	return out
}

// sectionHeader returns the ASCII header line of a section of a list
// snapshot.
func sectionHeader(title string) string {
	return "==== " + title + " " + strings.Repeat("=", max(0, 72-len(title)))
}

// listSnapshot renders the outcome of list l: its SDL, then its operator
// matrix.
func listSnapshot(l *easylist.CompiledList, sdl string) string {
	var sb strings.Builder
	sb.WriteString(sectionHeader("SDL generated by easylist-gqlgen"))
	sb.WriteString("\n\n")
	sb.WriteString(strings.TrimRight(sdl, "\n"))
	sb.WriteString("\n\n")
	sb.WriteString(sectionHeader("Operator matrix"))
	sb.WriteString("\n\n")
	sb.WriteString(matrixPreamble())
	for _, f := range l.Fields() {
		sb.WriteString("\n")
		sb.WriteString(fieldMatrix(l, f))
	}
	return sb.String()
}

// probeOps are the operators of the matrix, in the order printed. NULL
// probes use the operator spelled before " NULL" with a NULL value.
var probeOps = []string{
	"=", "!=", ">", ">=", "<", "<=",
	"CONTAINS", "EXCLUDES", "BETWEEN", "IN", "NOT IN",
	"= NULL", "!= NULL",
}

// listOps take a two-item list of the sample instead of the sample itself.
var listOps = map[string]bool{"BETWEEN": true, "IN": true, "NOT IN": true}

// samples holds the probe value of each field type, as filter text. Enum
// fields use their first declared value instead.
var samples = map[easylist.Type]string{
	easylist.Text:      `'x'`,
	easylist.Integer:   `1`,
	easylist.Float:     `1.5`,
	easylist.Numeric:   `1.5`,
	easylist.Boolean:   `TRUE`,
	easylist.Date:      `'2026-10-27'`,
	easylist.Timestamp: `'2026-10-27T10:00:00Z'`,
	easylist.UUID:      `'00000000-0000-4000-8000-000000000001'`,
}

// matrixPreamble explains how the matrix is built, so the outcome file
// shows the probe filters without the test at hand.
func matrixPreamble() string {
	var sb strings.Builder
	sb.WriteString(`For every field, each operator is probed with the filter
"<field>" <operator> <sample>, where BETWEEN, IN, and NOT IN take the list
(<sample>, <sample>) and the NULL rows use NULL as the value. The probe is
planned with CompiledList.Plan at the reference time and lowered with
sqlpg.Lower, which every driver uses to validate a plan. A row shows ok, or
the parse, plan, or lowering error. An array field uses its element type's
sample. Samples by type:
`)
	for typ := easylist.Text; typ.String() != "invalid"; typ++ {
		sample, ok := samples[typ]
		if typ == easylist.Enum {
			sample, ok = "the field's first declared value, quoted", true
		}
		if !ok {
			sample = "(none: every probe fails)"
		}
		fmt.Fprintf(&sb, "  %-10s %s\n", typ, sample)
	}
	return sb.String()
}

// fieldMatrix renders the block of field f: a header naming its shape,
// then one line per operator with the probe's outcome.
func fieldMatrix(l *easylist.CompiledList, f easylist.Field) string {
	shape := f.Type.String()
	if f.Array {
		shape += " array"
	}
	if f.Nullable {
		shape += ", nullable"
	}
	if f.Calculated() {
		shape += ", calculated"
	}
	var sb strings.Builder
	fmt.Fprintf(&sb, "%s (%s)\n", f.Name, shape)
	width := 0
	for _, op := range probeOps {
		width = max(width, len(op))
	}
	for _, op := range probeOps {
		fmt.Fprintf(&sb, "  %-*s  %s\n", width, op, probe(l, f, op))
	}
	return sb.String()
}

// probe plans the probe filter of operator op on field f and returns "ok"
// or "error: " and the first error.
func probe(l *easylist.CompiledList, f easylist.Field, op string) string {
	text := `"` + strings.ReplaceAll(f.Name, `"`, `""`) + `" ` + op
	if !strings.HasSuffix(op, " NULL") {
		sample := samples[f.Type]
		if f.Type == easylist.Enum && len(f.Values) > 0 {
			sample = "'" + strings.ReplaceAll(f.Values[0], "'", "''") + "'"
		}
		if listOps[op] {
			sample = "(" + sample + ", " + sample + ")"
		}
		text += " " + sample
	}
	expr, err := filter.Parse(text)
	if err != nil {
		return "error: " + err.Error()
	}
	plan, err := l.Plan(easylist.KindPage, easylist.Request{Filter: expr, Now: refTime})
	if err != nil {
		return "error: " + err.Error()
	}
	if _, err := sqlpg.Lower(plan); err != nil {
		return "error: " + err.Error()
	}
	return "ok"
}
